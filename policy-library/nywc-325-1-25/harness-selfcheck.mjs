#!/usr/bin/env node
/**
 * THE HARNESS, SHOWN FAILING BEFORE ANY DIVERGENCE FIGURE IS READ (12 NYCRR 325-1.25).
 * One mutation, in memory, into the regulation register: the constant 45 in the binding
 * `action_within_45_of_submission` becomes 40. Every determination whose carrier acted between day
 * 41 and day 45 from submission must move on the clauses that read that binding ((c)(3) barred,
 * (d)(1), (e)(1), (f)(1)). The comparator must report the divergence on those clauses and exit
 * nonzero; an unmutated re-run must report zero. Exit 2 and STOP the sequence if not.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { replayAll } from '../nywc-12nycrr-fee/replay.mjs';
import { compareRuns, render } from '../nywc-12nycrr-fee/compare.mjs';
import { populationOf, figure, renderFigure, populationMarker } from '../nywc-12nycrr-fee/figure.mjs';
const HERE = new URL('.', import.meta.url).pathname;
const REG = `${HERE}/versions/regulation/register.json`;
const DET = JSON.parse(readFileSync(`${HERE}/determinations.json`, 'utf8')); const det = DET.determinations; const pop = populationOf(DET, HERE);
const load = () => JSON.parse(readFileSync(REG, 'utf8'));
const SITE = 'bindings.action_within_45_of_submission (the 45)';
const mutate = (reg) => { const a = reg.bindings.action_within_45_of_submission.left.args; if (a[2].op !== 'const' || a[2].value !== 45) throw new Error('the mutation site moved'); a[2].value = 40; return reg; };
const baseline = replayAll(load(), det), mutated = replayAll(mutate(load()), det), rerun = replayAll(load(), det);
const repM = compareRuns(baseline, mutated, { left: 'regulation (unmutated)', right: `regulation MUTATED: 45 -> 40 at ${SITE}` });
const repR = compareRuns(baseline, rerun, { left: 'regulation (unmutated)', right: 'regulation (unmutated, second run)' });
const textM = render(repM, pop), textR = render(repR, pop);
const divergeM = Object.values(repM.byClause).some((c) => c.diverge || c.absent_left || c.absent_right);
const divergeR = Object.values(repR.byClause).some((c) => c.diverge || c.absent_left || c.absent_right);
const moved = Object.entries(repM.byClause).filter(([, c]) => c.diverge).map(([id, c]) => ({ id, n: c.diverge }));
const total = moved.reduce((a, m) => a + m.n, 0);
const ok = divergeM && moved.length > 0 && !divergeR;
const md = `# Harness self-check: the comparator shown failing (12 NYCRR 325-1.25)

Generated by \`harness-selfcheck.mjs\` on the committed \`determinations.json\` (${det.length} determinations). Do not edit by hand: rerun it.

## 1. ONE CONSTANT OF THE REGULATION REGISTER

**What was perturbed.** ${SITE}, set to 40. In memory; the file is untouched. The binding is read by (c)(3) late-objection-barred, (d)(1) award-availability, (e)(1) arbitration-availability and, through it, by the timely-valuation-notice binding.

\`\`\`
${textM}
\`\`\`

Determinations changed: **${renderFigure(figure(repM.determinationsDiverging, det.length, pop))}**, on ${moved.length} clause(s): ${moved.map((m) => `\`${m.id}\` (${m.n})`).join(', ')}. Comparator exit on the mutated comparison: **${divergeM ? '1 (nonzero, as required)' : '0 (FAILED TO DETECT)'}**.

## 2. THE UNMUTATED REGISTER, TWICE

\`\`\`
${textR}
\`\`\`

Comparator exit on the unmutated comparison: **${divergeR ? '1 (FALSE POSITIVE)' : '0 (as required)'}**.

## Verdict

${populationMarker(pop)}

${ok ? `**SHOWN FAILING, THEN CLEAN.** The comparator detects a single-constant mutation on the clauses that read it (${repM.determinationsDiverging}/${det.length} determinations) and exits nonzero, and reports zero divergence on an identical re-run. The divergence figures in DIVERGENCE.md may be read.` : '**STOP.** The self-check did not pass. No divergence figure after this point is interpretable.'}
`;
writeFileSync(`${HERE}/HARNESS-SELF-CHECK.md`, md);
writeFileSync(`${HERE}/out/selfcheck.json`, JSON.stringify({ $derived_by: 'harness-selfcheck.mjs', population: pop, denominator: det.length, figures: [repM.determinationsDiverging, det.length - repM.determinationsDiverging, 0, ...moved.map((m) => m.n), ...Object.values(repM.byClause).map((c) => c.agree)], mutated_site: SITE, determinations_changed: repM.determinationsDiverging, moved, rerun_diverging: 0, mutated_exit: divergeM ? 1 : 0, rerun_exit: divergeR ? 1 : 0 }, null, 1) + '\n');
console.log(`self-check: mutated diverges=${divergeM} determinations=${repM.determinationsDiverging} clauses=${moved.length} (${moved.map((m) => m.id.split('/').slice(1).join('/') + ':' + m.n).join(', ')}); rerun diverges=${divergeR}`);
if (!ok) { console.error('SELF-CHECK FAILED: stop the sequence'); process.exit(2); }
console.log('SELF-CHECK PASSED: written HARNESS-SELF-CHECK.md');
