#!/usr/bin/env node
/**
 * THE FIGURE CAVEAT, SHOWN REFUSING. Writes FIGURE-CAVEAT.md with three verbatim outputs:
 *   1. renderFigure on a figure built without a population -> throws;
 *   2. check-figures.mjs over a temporary surface carrying one figure bare -> exit 1, naming it;
 *   3. check-figures.mjs over the directory as committed -> exit 0.
 * A control that has only ever passed is not a control.
 */
import { readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { figure, renderFigure, populationOf, populationMarker } from './figure.mjs';
const HERE = new URL('.', import.meta.url).pathname;
const DET = JSON.parse(readFileSync(`${HERE}/determinations.json`, 'utf8'));
const pop = populationOf(DET);
const df = JSON.parse(readFileSync(`${HERE}/out/defensibility.json`, 'utf8'));
const n = df.denominator, k = df.cites_version_not_in_force.union;

// The previous run's FIGURE-CAVEAT.md quotes the scanner's own FAIL lines, which carry figure
// strings; scanning it as if it were a surface of the committed directory reported those quoted
// lines as bare (they were, in the stale file). Neutralise this script's own output before the
// scans, so what the scans see is the directory without it; the fresh file is written last.
writeFileSync(`${HERE}/FIGURE-CAVEAT.md`, '# The synthetic caveat, structural: shown refusing\n\n(being regenerated by show-figure-refusal.mjs)\n');

// 1. programmatic
let out1;
try { renderFigure({ k, n, pct: (100 * k) / n }); out1 = 'RENDERED (FAILED TO REFUSE)'; } catch (e) { out1 = `threw: ${e.message}`; }
let out1b;
try { figure(k, n, undefined); out1b = 'BUILT (FAILED TO REFUSE)'; } catch (e) { out1b = `threw: ${e.message}`; }
const ok1 = renderFigure(figure(k, n, pop));

// 2. a bare figure on a temporary surface
const demo = `${HERE}/out/bare-figure-demo.md`;
writeFileSync(demo, `# A figure that travelled\n\nThe register found ${k}/${n} (${((100 * k) / n).toFixed(1)}%) cite a version not in force.\n`);
const r2 = spawnSync('node', [`${HERE}/check-figures.mjs`, '--demo', demo], { encoding: 'utf8' });
unlinkSync(demo);
// 3. clean
const r3 = spawnSync('node', [`${HERE}/check-figures.mjs`], { encoding: 'utf8' });

const md = `# The synthetic caveat, structural: shown refusing

Generated by \`show-figure-refusal.mjs\`. Do not edit by hand: rerun it.

The figures over the synthetic set (\`defensibility.mjs\`, \`compare.mjs\`) are built with \`figure(k, n, population)\` and rendered only through \`renderFigure\`, which throws unless the figure carries the population block and that block's parameter digest equals the live digest of the generator's header. Every rendered figure carries the marker \`[population: …]\` beside it, and \`check-figures.mjs\` scans every surface in this directory for the figure strings the reports produced and fails on any occurrence whose section has no marker or a stale one.

## 1. A figure built or rendered without its population

\`\`\`
figure(${k}, ${n}, undefined)          -> ${out1b}
renderFigure({ k: ${k}, n: ${n} })     -> ${out1}
renderFigure(figure(${k}, ${n}, pop)) -> ${ok1}
\`\`\`

## 2. A surface carrying one figure bare (temporary file, removed afterwards)

The file contained the line: \`The register found ${k}/${n} (${((100 * k) / n).toFixed(1)}%) cite a version not in force.\` ${populationMarker(pop)}

\`\`\`
${r2.stdout.trim()}
[exit ${r2.status}]
\`\`\`

## 3. The directory as committed

${populationMarker(pop)}

\`\`\`
${r3.stdout.trim()}
[exit ${r3.status}]
\`\`\`

## Verdict

${r2.status === 1 && r3.status === 0 && out1.startsWith('threw') && out1b.startsWith('threw') ? '**SHOWN REFUSING, THEN CLEAN.** The programmatic path throws on a figure without its population; the scanner fails a surface carrying a bare figure and names the file and line; the committed directory passes.' : '**STOP.** The caveat is not structural: one of the three checks did not behave as required.'}
`;
writeFileSync(`${HERE}/FIGURE-CAVEAT.md`, md);
console.log(md);
if (!(r2.status === 1 && r3.status === 0 && out1.startsWith('threw') && out1b.startsWith('threw'))) process.exit(2);
