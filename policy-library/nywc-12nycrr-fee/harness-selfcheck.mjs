#!/usr/bin/env node
/**
 * THE HARNESS, SHOWN FAILING BEFORE ANY DIVERGENCE FIGURE IS READ.
 *
 * Injects ONE mutation into the in-force register IN MEMORY: the constant 85 in
 * 12nycrr/329-1.3/c/3/eighty-five-percent becomes 80. Under that mutation every determination
 * paying exactly 85 percent of its bound with CQ or CO billed must flip from equal to not_equal
 * (and one paying exactly 80 percent, if any, the other way). The comparator must report the
 * divergence ON THAT CLAUSE and exit nonzero. Then the unmutated register is replayed a second
 * time and compared with the first run: the comparator must report zero divergence and exit 0.
 *
 * Both outputs are written VERBATIM to HARNESS-SELF-CHECK.md. If the mutated comparison does not
 * diverge on at least one determination, this script exits 2 and the sequence STOPS: every figure
 * after it would be uninterpretable.
 *
 *   node harness-selfcheck.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { replayAll } from './replay.mjs';
import { compareRuns, render } from './compare.mjs';
const HERE = new URL('.', import.meta.url).pathname;
const REG = `${HERE}/versions/in-force/register.json`;
import { populationOf, figure, renderFigure, populationMarker } from './figure.mjs';
const DET = JSON.parse(readFileSync(`${HERE}/determinations.json`, 'utf8'));
const det = DET.determinations;
const pop = populationOf(DET);

const load = () => JSON.parse(readFileSync(REG, 'utf8'));
const MUTANT_CLAUSE = '12nycrr/329-1.3/c/3/eighty-five-percent';
const mutate = (reg) => {
  const c = reg.clauses.find((x) => x.id === MUTANT_CLAUSE);
  const args = c.evaluate.result.compute.args;
  if (args[2].op !== 'const' || args[2].value !== 85) throw new Error('the mutation site is not where this script expects it; the register moved');
  args[2].value = 80;
  return reg;
};

const baseline = replayAll(load(), det);
const mutated = replayAll(mutate(load()), det);
const rerun = replayAll(load(), det);

const repM = compareRuns(baseline, mutated, { left: 'in-force (unmutated)', right: 'in-force MUTATED: 85 -> 80 at ' + MUTANT_CLAUSE });
const repR = compareRuns(baseline, rerun, { left: 'in-force (unmutated)', right: 'in-force (unmutated, second run)' });
const textM = render(repM, pop), textR = render(repR, pop);
const divergeM = Object.values(repM.byClause).some((c) => c.diverge || c.absent_left || c.absent_right);
const divergeR = Object.values(repR.byClause).some((c) => c.diverge || c.absent_left || c.absent_right);
const onClause = repM.byClause[MUTANT_CLAUSE]?.diverge ?? 0;
const offClause = Object.entries(repM.byClause).filter(([id, c]) => id !== MUTANT_CLAUSE && c.diverge).map(([id, c]) => `${id} (${c.diverge})`);

const md = `# Harness self-check: the comparator shown failing

Generated by \`harness-selfcheck.mjs\` on the committed \`determinations.json\` (${det.length} determinations). Do not edit by hand: rerun it.

An instrument that cannot fail is not evidence. Before any divergence figure from \`compare.mjs\` is read, one mutation is injected into the in-force register in memory and the comparator must catch it; then the unmutated register is replayed twice and the comparator must find nothing.

## 1. ONE CONSTANT OF THE IN-FORCE REGISTER

**What was perturbed.** \`${MUTANT_CLAUSE}\`, the argument \`85\` of \`amount_fraction_of\`, set to \`80\`. Nothing else. The mutated register exists only in memory; the file on disk is untouched.

\`\`\`
${textM}
\`\`\`

Determinations changed on the mutated clause: **${renderFigure(figure(onClause, det.length, pop))}**; unchanged on it: ${renderFigure(figure(det.length - onClause, det.length, pop), { marker: false })}. Determinations changed on any OTHER clause: **${offClause.length ? offClause.join(', ') : 'none'}**${offClause.length ? ' (a mutation of one constant reaching another clause would mean the clauses are coupled through a binding, which they are not; this is reported so a reader can see it was checked)' : ''}.

Comparator exit status on the mutated comparison: **${divergeM ? '1 (nonzero, as required)' : '0 (FAILED TO DETECT)'}**.

## 2. THE UNMUTATED REGISTER, TWICE

\`\`\`
${textR}
\`\`\`

Comparator exit status on the unmutated comparison: **${divergeR ? '1 (FALSE POSITIVE)' : '0 (as required)'}**.

## Verdict

${populationMarker(pop)}

${divergeM && onClause > 0 && !divergeR ? `**SHOWN FAILING, THEN CLEAN.** The comparator detects a single-constant mutation on the clause that carries it (${onClause}/${det.length} determinations) and exits nonzero, and reports zero divergence on an identical re-run. The divergence figures in DIVERGENCE.md may be read.` : '**STOP.** The self-check did not pass. No divergence figure after this point is interpretable.'}
`;
writeFileSync(`${HERE}/HARNESS-SELF-CHECK.md`, md);
writeFileSync(`${HERE}/out/selfcheck.json`, JSON.stringify({ $derived_by: 'harness-selfcheck.mjs', population: pop, denominator: det.length, figures: [onClause, det.length - onClause, 0], mutated_clause: MUTANT_CLAUSE, changed_on_clause: onClause, unchanged_on_clause: det.length - onClause, changed_off_clause: offClause.length, rerun_diverging: 0, mutated_exit: divergeM ? 1 : 0, rerun_exit: divergeR ? 1 : 0 }, null, 1) + '\n');
console.log(textM); console.log(''); console.log(textR);
console.log(`\nself-check: mutated diverges=${divergeM} on-clause=${onClause} off-clause=${offClause.length}; rerun diverges=${divergeR}`);
if (!(divergeM && onClause > 0 && !divergeR)) { console.error('SELF-CHECK FAILED: stop the sequence'); process.exit(2); }
console.log('SELF-CHECK PASSED: written HARNESS-SELF-CHECK.md');
